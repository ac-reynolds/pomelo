#!/usr/bin/env python3
"""Convert a compiled SPIR-V module into a C++ source file of uint32_t words."""

import argparse
from pathlib import Path
import re
import struct


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="Compiled .spv file")
    parser.add_argument("output", type=Path, help="Generated C++ source file")
    parser.add_argument("--symbol", required=True, help="C++ array name")
    parser.add_argument("--header", required=True, help="Include path of the handwritten declaration header")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", args.symbol):
        parser.error("--symbol must be a C++ identifier")
    if not re.fullmatch(r"[A-Za-z0-9_./-]+", args.header):
        parser.error("--header must be an include path using letters, digits, underscores, dots, slashes, or hyphens")

    try:
        bytecode = args.input.read_bytes()
        if len(bytecode) < 20 or len(bytecode) % 4:
            parser.error("SPIR-V must contain a five-word header and whole 32-bit words")
        if bytecode[:4] != b"\x03\x02\x23\x07":
            parser.error("expected little-endian SPIR-V magic number")

        words = [word for (word,) in struct.iter_unpack("<I", bytecode)]
        rows = [
            "    " + ", ".join(f"0x{word:08x}u" for word in words[start:start + 8]) + ","
            for start in range(0, len(words), 8)
        ]
        source = (
            "// Generated by deployment/embed_spirv.py. Do not edit.\n"
            f'#include "{args.header}"\n\n'
            f"const std::uint32_t {args.symbol}[] = {{\n"
            + "\n".join(rows)
            + "\n};\n"
            + f"const std::size_t {args.symbol}_size = sizeof({args.symbol});\n"
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source, encoding="utf-8")
    except OSError as error:
        parser.exit(1, f"{parser.prog}: {error}\n")


if __name__ == "__main__":
    main()
